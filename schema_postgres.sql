CREATE TABLE IF NOT EXISTS products (
 sku TEXT PRIMARY KEY, product_name TEXT, cate_code TEXT, cate_name TEXT, brand TEXT, cm TEXT,
 product_id TEXT, model_id TEXT, model_name TEXT, list_price DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS cost_fund (
 sku TEXT PRIMARY KEY, cost DOUBLE PRECISION, fund DOUBLE PRECISION,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS commission (
 cate_code TEXT PRIMARY KEY, commission_rate DOUBLE PRECISION,
 packing_fee DOUBLE PRECISION, cm TEXT
);
CREATE TABLE IF NOT EXISTS inventory (
 sku TEXT PRIMARY KEY, hcm DOUBLE PRECISION DEFAULT 0, hn DOUBLE PRECISION DEFAULT 0,
 danang DOUBLE PRECISION DEFAULT 0, total_3 DOUBLE PRECISION DEFAULT 0,
 total_company DOUBLE PRECISION DEFAULT 0, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS fee_settings (
 id INTEGER PRIMARY KEY, transaction_rate DOUBLE PRECISION, voucher_rate DOUBLE PRECISION,
 voucher_cap DOUBLE PRECISION, infrastructure_fee DOUBLE PRECISION, pi_ship DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS deals (
 sku TEXT PRIMARY KEY, daily_price DOUBLE PRECISION, margin DOUBLE PRECISION,
 est_gp DOUBLE PRECISION, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS price_history (
 id BIGSERIAL PRIMARY KEY, sku TEXT, daily_price DOUBLE PRECISION,
 margin DOUBLE PRECISION, est_gp DOUBLE PRECISION,
 changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS import_log (
 id BIGSERIAL PRIMARY KEY, source_name TEXT, rows_read INTEGER, rows_saved INTEGER,
 note TEXT, imported_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
